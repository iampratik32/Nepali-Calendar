#!/usr/bin/env python3
"""Regenerate app/src/main/java/app/patro/bs/BsData.kt from data/calendar.json.

Usage: python3 scripts/gen_bsdata.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "data/calendar.json").read_text())
years = sorted(int(k) for k in data if k.isdigit())
assert years == list(range(years[0], years[-1] + 1)), "years must be contiguous"
packed = ""
for y in years:
    months = data[str(y)]
    assert len(months) == 12 and all(29 <= m <= 32 for m in months), y
    packed += "".join(str(m - 29) for m in months)
lines = [packed[i:i + 72] for i in range(0, len(packed), 72)]
body = " +\n".join('        "%s"' % line for line in lines)
out = f'''package app.patro.bs

/**
 * Bundled BS month lengths, BS {years[0]}–{years[-1]}.
 *
 * Source: sonill/nepali-dates `data/calendar-data.json` (MIT), commit 3817e07.
 * Encoding: 12 chars per year, each char = (days in month − 29), so '0'..'3' = 29..32 days.
 * Generated by `scripts/gen_bsdata.py` from `data/calendar.json`; Sync can override it at runtime.
 */
internal object BsData {{
    const val FIRST_YEAR = {years[0]}
    const val PACKED =
{body}
}}
'''
(root / "app/src/main/java/app/patro/bs/BsData.kt").write_text(out)
print(f"wrote {len(years)} years")
